assert.match(ai, /workflow_plan_id/);
assert.match(ai, /approved=allItems\.filter/);
assert.match(ai, /discarded=allItems\.filter/);
assert.match(ai, /app\.post\('\/api\/ai\/course-workflow\/repair'/);
assert.match(ai, /linked_existing/);
assert.match(ai, /diagnostics:\{book_sessions:sessions\.length,book_activities:allItems\.length/);
assert.match(ui, /async function openCourseWorkflow\(courseId,initialTab='pending'\)/);
assert.match(ui, /data-workflow-tab="\$\{tab\}"/);
assert.match(ui, /data-workflow-repair="\$\{courseId\}"/);
