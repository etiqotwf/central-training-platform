'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const server = fs.readFileSync(path.join(root,'server.js'),'utf8');
const sync = fs.readFileSync(path.join(root,'scripts','live-google-sheets-sync.js'),'utf8');
const index = fs.readFileSync(path.join(root,'public','index.html'),'utf8');
const ai = fs.readFileSync(path.join(root,'ai','index.js'),'utf8');
assert.match(server,/api\/master-control\/unlock/);
assert.match(server,/api\/storage-encryption/);
assert.match(server,/api\/platform-permissions/);
assert.match(server,/require\('\.\/intelligence'\)/);
assert.match(server,/api\/admin\/google-sheets-status/);
assert.match(sync,/Never clears live sheet data before a successful replacement write/);
assert.match(sync,/checkSnapshotSafety/);
const syncNow = sync.match(/async function syncNow\(\) \{([\s\S]*?)\n\}/)?.[1] || '';
assert.match(syncNow,/values\.batchUpdate\(/);
assert.ok(syncNow.indexOf('batchUpdate') < syncNow.indexOf('scheduleTailCleanup'), 'live data is written before optional tail cleanup');
assert.doesNotMatch(syncNow,/batchClear/, 'syncNow must never clear live tabs before writing');
assert.match(sync,/ENCRYPTION_PREFIX = 'enc:v1:'/);
assert.match(sync,/encryptCell\(row\[c\]\)/);
assert.match(sync,/decryptCell\(row\[ix\]\)/);
assert.match(sync,/setStorageEncryption/);
assert.match(sync,/getStorageEncryptionStatus/);
assert.match(index,/central-training-logo-source\.png/);
assert.match(index,/DECRYPT/);
assert.match(ai,/منصة الإدارة المركزية للتدريب/);
assert.match(ai,/course-plan\/apply/);
assert.ok(fs.existsSync(path.join(root,'learning','archive.js')),'Central archive must remain');
assert.ok(fs.existsSync(path.join(root,'intelligence.js')),'Central intelligence module must remain');
assert.ok(fs.existsSync(path.join(root,'DATA_ENCRYPTION_SETUP.md')),'Central encryption docs must remain');
console.log('Central V41 integration and preservation tests passed.');
